"""Build the rule-verifiable GRPO training set for Phase 3.

Every sample is a prompt + a programmatically checkable answer, in the same
four families as the held-out benchmark (arithmetic / format / logic / multistep).
Answers are generated by code, so the reward is exact-match, never an LLM judge.

Output: D:\llm-rl-lab\data\grpo\train_grpo.jsonl  (jsonl: {id, family, prompt, answer})
plus D:\llm-rl-lab\data\grpo\train_grpo_stats.json

Usage: python build_grpo_data.py --per-family 200 --seed 42
"""
import argparse
import json
import os
import random

p = argparse.ArgumentParser()
p.add_argument('--per-family', type=int, default=200)
p.add_argument('--seed', type=int, default=42)
p.add_argument('--out', default=os.path.join(PROJECT_ROOT, 'data', 'grpo', 'train_grpo.jsonl'))
args = p.parse_args()

rng = random.Random(args.seed)


def gen_arithmetic():
    """Single-digit +- and small 2-digit cases, answer an integer."""
    kind = rng.random()
    if kind < 0.6:
        a, b = rng.randint(0, 9), rng.randint(0, 9)
        op = rng.choice(['+', '-'])
        ans = a + b if op == '+' else a - b
        q = f'{a} {op} {b} 等于多少？请只回复一个数字，不要写任何解释或计算过程。'
    elif kind < 0.85:
        a, b = rng.randint(0, 20), rng.randint(0, 20)
        op = rng.choice(['+', '-'])
        ans = a + b if op == '+' else a - b
        q = f'{a} {op} {b} 等于多少？请只回复一个数字，不要写任何解释或计算过程。'
    else:
        a, b = rng.randint(2, 9), rng.randint(2, 9)
        ans = a * b
        q = f'{a} × {b} 等于多少？请只回复一个数字，不要写任何解释或计算过程。'
    if ans < 0:
        q = q.replace('请只回复一个数字', '请只回复一个数字，若为负数请带上负号')
    return q, str(ans)


def gen_format():
    kind = rng.random()
    if kind < 0.4:
        a, b = rng.randint(0, 9), rng.randint(0, 9)
        ans = a + b
        q = ('请输出一个 JSON 对象，且只包含键 "sum"，值为 %d+%d 的结果。'
             '不要输出任何其他文字。例如：{"sum": 3}' % (a, b))
        return q, json.dumps({'sum': ans}, ensure_ascii=False, separators=(',', ':'))
    if kind < 0.7:
        a, b = rng.randint(0, 9), rng.randint(0, 9)
        ans = 'YES' if a > b else 'NO'
        q = f'{a} 是否大于 {b}？只回答 YES 或 NO，不要输出其他任何内容。'
        return q, ans
    a, b = rng.randint(0, 9), rng.randint(0, 9)
    correct = a + b
    choices = [correct, correct + 1, max(0, correct - 1)]
    rng.shuffle(choices)
    letters = 'ABC'
    idx = choices.index(correct)
    q = (f'{a} + {b} = ? 请从下面三个选项中选择一个，只回答对应的字母（A、B 或 C）：'
         f'A. {choices[0]}  B. {choices[1]}  C. {choices[2]}')
    return q, letters[idx]


def gen_logic():
    kind = rng.random()
    a, b, c = rng.sample(range(1, 20), 3)
    if kind < 0.35:
        # ordering: who is largest
        names = ['A', 'B', 'C']
        order = rng.sample(range(3), 3)  # ranking
        vals = {names[i]: order[i] for i in range(3)}
        # build statements: highest rank wins
        srt = sorted(names, key=lambda n: -vals[n])
        q = (f'{srt[0]} 比 {srt[1]} 大，{srt[1]} 比 {srt[2]} 大。'
             f'谁最小？只回答 {srt[0]}、{srt[1]} 或 {srt[2]} 中的一个字母。')
        return q, srt[2]
    if kind < 0.7:
        # parity
        n = rng.randint(1, 30)
        q = f'{n} 是奇数还是偶数？只回答"奇数"或"偶数"。'
        return q, '奇数' if n % 2 else '偶数'
    # max of three
    nums = [rng.randint(0, 30) for _ in range(3)]
    q = (f'这三个数中最大的是哪个：{nums[0]}, {nums[1]}, {nums[2]}？'
         f'请只回复那个数字，不要写任何解释。')
    return q, str(max(nums))


def gen_multistep():
    kind = rng.random()
    if kind < 0.4:
        a, b, c = rng.randint(1, 9), rng.randint(1, 9), rng.randint(2, 5)
        ans = (a + b) * c
        q = f'先计算 {a} + {b}，再把结果乘以 {c}，最终结果是多少？请只回复一个数字。'
        return q, str(ans)
    if kind < 0.7:
        n = rng.randint(2, 12)
        ans = n * (n + 1) // 2
        q = f'前 {n} 个正整数的和是多少？请只回复一个数字。'
        return q, str(ans)
    a, b = rng.randint(2, 9), rng.randint(2, 9)
    ans = a * b - a
    q = f'{a} 乘以 {b} 再减去 {a}，结果是多少？请只回复一个数字。'
    return q, str(ans)


gens = {'arithmetic': gen_arithmetic, 'format': gen_format,
        'logic': gen_logic, 'multistep': gen_multistep}
counts = {'arithmetic': args.per_family, 'format': int(args.per_family * 0.75),
          'logic': int(args.per_family * 0.75), 'multistep': int(args.per_family * 0.5)}

os.makedirs(os.path.dirname(args.out), exist_ok=True)
records, seen = [], set()
for fam, n in counts.items():
    made = 0
    tries = 0
    while made < n and tries < n * 50:
        tries += 1
        q, a = gens[fam]()
        if (q, a) in seen:
            continue
        seen.add((q, a))
        records.append({'id': f'{fam}_{made:04d}', 'family': fam, 'prompt': q, 'answer': a})
        made += 1
rng.shuffle(records)

with open(args.out, 'w', encoding='utf-8', newline='\n') as f:
    for r in records:
        f.write(json.dumps(r, ensure_ascii=False) + '\n')

stats = {'total': len(records), 'per_family': {f: sum(1 for r in records if r['family'] == f) for f in counts},
         'seed': args.seed, 'out': args.out}
print(json.dumps(stats, ensure_ascii=False, indent=2))
with open(os.path.join(os.path.dirname(args.out), 'train_grpo_stats.json'), 'w', encoding='utf-8') as f:
    json.dump(stats, f, ensure_ascii=False, indent=2)
